// Define coefficients for linear multistep methods
struct Coefficients_LMM {
    vector<double> alpha;
    vector<double> beta;
    int p, s;
};
typedef struct Coefficients_LMM Coefficients_LMM;
// Return the index of the coefficients for a given order p 
inline int p2index(const vector<Coefficients_LMM>& Coefficients_LMM, int p) { 
    int size = Coefficients_LMM.size();
    for (int i = 0; i < size; i++){
        if (Coefficients_LMM[i].p == p) return i;
    }
    return -1;
}
